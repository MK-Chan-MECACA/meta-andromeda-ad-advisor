import type { AnalysisResult } from "@/lib/analysis-schema";

function liveLabel(value: AnalysisResult["scorecard"]["livePerformance"]) {
  switch (value) {
    case "Working":
      return "Working";
    case "NotWorking":
      return "Not working";
    case "Learning":
      return "Learning";
    default:
      return "Unknown";
  }
}

/** Notion / docs-friendly markdown report from a structured analysis. */
export function analysisToMarkdown(analysis: AnalysisResult): string {
  const { eligibility, retrieval, ranking, learning, scorecard, portfolio, signals } =
    analysis;

  const lines: string[] = [
    `# Andromeda verdict: ${analysis.verdict.replace("_", " ")}`,
    "",
    analysis.bottomLine,
    "",
    "## Pipeline",
    "Eligibility → Retrieval MoE → Ranking (GEM/Lattice) → Auction → Learning",
    "",
    "## Scorecard",
    `| Dimension | Grade | Note |`,
    `|---|---|---|`,
    `| Setup Andromeda-aligned? | ${scorecard.setupAlignment} | ${scorecard.setupAlignmentNote} |`,
    `| Creative diversity | ${scorecard.creativeDiversity} | ${scorecard.creativeDiversityNote} |`,
    `| Objective ↔ offer fit | ${scorecard.objectiveOfferFit} | ${scorecard.objectiveOfferFitNote} |`,
    `| Live performance | ${liveLabel(scorecard.livePerformance)} | ${scorecard.livePerformanceNote} |`,
    `| Advantage+ adoption | ${signals.advantagePlus.grade} | ${signals.advantagePlus.note} |`,
    `| Signal hygiene | ${signals.signalHygiene.grade} | ${signals.signalHygiene.note} |`,
    "",
    "## What went well",
    ...analysis.whatWentWell.map((item) => `- ${item}`),
    "",
    "## What went wrong",
    ...analysis.whatWentWrong.map((item) => `- ${item}`),
    "",
    "## Portfolio / diversity",
    `- Mode: ${portfolio.mode}`,
    `- True tickets: ${portfolio.trueTicketCount}`,
    `- ${portfolio.summary}`,
    `- Format: ${portfolio.diversityMatrix.format}`,
    `- Persona: ${portfolio.diversityMatrix.persona}`,
    `- Environment: ${portfolio.diversityMatrix.environment}`,
    `- Benefit: ${portfolio.diversityMatrix.benefit}`,
    `- Diversification grade: ${portfolio.diversityMatrix.grade}`,
    "",
    "### Clusters",
    ...portfolio.clusters.map(
      (c) =>
        `- **${c.label}** (${c.isDistinctTicket ? "distinct ticket" : "collapsed"}): ${c.members.join(", ")} — ${c.note}`,
    ),
  ];

  if (portfolio.collapsedDuplicates.length) {
    lines.push("", "### Collapsed duplicates");
    lines.push(...portfolio.collapsedDuplicates.map((d) => `- ${d}`));
  }

  lines.push(
    "",
    "## Signals & Advantage+",
    `- Value optimization: ${signals.valueOptFit}`,
    `- Post-click CX: ${signals.cxRisk}`,
    "",
    "### Checklist",
    ...signals.checklist.map(
      (c) => `- [${c.status}] **${c.item}** — ${c.note}`,
    ),
    "",
    "## Stage 0 — Eligibility",
    eligibility.summary,
    `Eligibility breadth: ${eligibility.eligibilityBreadth}`,
  );

  if (eligibility.blockers.length) {
    lines.push(...eligibility.blockers.map((b) => `- Blocker: ${b}`));
  }

  lines.push(
    "",
    "## Stage 1 — Retrieval MoE",
    `- Semantic node: ${retrieval.semanticNode}`,
    `- Ticket count: ${retrieval.ticketCount} — ${retrieval.ticketRationale}`,
    `- Expert coverage: ${retrieval.expertCoverage}`,
    `- Semantic clarity: ${retrieval.semanticClarity.grade} — ${retrieval.semanticClarity.note}`,
    `- Cold-start: ${retrieval.coldStartReadiness}`,
    `- Cage check: ${retrieval.cageCheck}`,
    `- Congruence: ${retrieval.congruence}`,
    `- Grade: ${retrieval.grade}`,
    "",
    "## Stage 2 — Ranking & auction",
    `- EAR fit: ${ranking.earFit}`,
    `- Quality: ${ranking.quality}`,
    `- Formula risk: ${ranking.formulaRisk}`,
    "",
    "## Learning & timing",
    learning.summary,
    `Budget guidance: ${learning.budgetGuidance}`,
    "",
    "## Fixes (priority order)",
    ...analysis.fixes
      .slice()
      .sort((a, b) => a.priority - b.priority)
      .map((f) => `${f.priority}. **${f.action}** — ${f.why}`),
  );

  if (analysis.missingInputs.length) {
    lines.push("", "## What I still need");
    lines.push(...analysis.missingInputs.map((m) => `- ${m}`));
  }

  lines.push(
    "",
    "---",
    "_Generated by Andromeda Ad Advisor · reverse-engineered from published Meta Engineering/Business posts (Oct 2026). Not official Meta diagnostics._",
    "",
  );

  return lines.join("\n");
}

export function downloadMarkdown(filename: string, markdown: string) {
  const blob = new Blob([markdown], { type: "text/markdown;charset=utf-8" });
  const url = URL.createObjectURL(blob);
  const a = document.createElement("a");
  a.href = url;
  a.download = filename;
  a.click();
  URL.revokeObjectURL(url);
}
